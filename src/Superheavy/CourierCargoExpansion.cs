using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using HarmonyLib;
using UnityEngine;
using Object = UnityEngine.Object;

namespace Japensou.NuclearOption.CurrentDamage
{
    // Owner request 25/11/2026 ("Coloca o Spearhead MBT (com retro) como opção de carga, reduz também o tempo de lançamento
    // das cargas ... adiciona mais variedades de armas à bomb bay, vê também se dá pra adicionar algo que aceite armamentos
    // de outros mods"). The family DLL stays byte-identical; everything here works on the Courier's runtime data.
    //
    // 1. Spearhead MBT (native MBT1) as cargo. The family already builds vehicle cargo at runtime
    //    (SuperheavyQolStores.BuildCargo: primary-LOD art, native MountedCargo, measured and fitted by the spatial plan);
    //    it is called with the Courier's Type-12 MBT cargo as donor. The Spearhead measures about 9.7 x 4.2 x 4.3 m, above
    //    the 4.07 m standard ramp height, and the hold study (ANALISE_FISICA, Spearhead row) found its separate hull and
    //    turret envelopes clear the open ramp on the centreline when it faces the nose and leaves in reverse, which is the
    //    pose of every Courier vehicle cargo. The centreline clearance accepts it with those limits. With the Cargo Retro
    //    Kit installed its kit variant ("Spearhead MBT [Retro Kit]") is generated by the kit and preferred on the Courier.
    // 2. Release tempo. Each load waited railDelay 1 s and slid out at 5 m/s (air ETA about 9.5-10 s in player logs), and
    //    a vehicle unloaded on the ground was pushed clear at 2 m/s over 20 m (10 s) before the next could leave. Courier
    //    loads now start after .25 s and slide at 12 m/s in the air and 7 m/s on the ground, and are pushed clear at 5 m/s.
    //    The family airdrop planner reads these same fields when it plans the release, so its prediction stays exact. In the
    //    air a press made while the rail is busy is queued like on the ground (CourierGroundUnload), so the loads leave in
    //    sequence without waiting for the player.
    // 3. Weapons bay. Every internal weapon registered in the game (useWeaponDoors), stock or from any other mod, that is
    //    not already offered and is not excluded by the 16/11 owner decision (PAB-125, PAB-250, air-to-air missiles) is
    //    offered in the Ventral Weapons Bay in the validated round positions of a larger existing bay weapon (see
    //    PopulateBay). Weapons registered later by other mods are picked up whenever the loadout menu opens or a loadout
    //    is checked.
    internal static class CourierCargoExpansion
    {
        internal const string CourierKey = "jp_superheavy_ground_test";
        internal const string SpearheadKey = "jp_superheavy_cargo_mbt1";
        private const string DonorKey = "jp_superheavy_cargo_mbt";
        private const string BayPrefix = "jp_courier_bay_";
        internal const float AirRailSpeed = 12f, GroundRailSpeed = 7f, RailDelay = .25f, PushSpeed = 5f;

        private static readonly AccessTools.FieldRef<MountedCargo, float> CargoRailSpeed = AccessTools.FieldRefAccess<MountedCargo, float>("railSpeed");
        private static readonly AccessTools.FieldRef<MountedCargo, float> CargoRailDelay = AccessTools.FieldRefAccess<MountedCargo, float>("railDelay");
        private static readonly AccessTools.FieldRef<MountedCargo, float> CargoPushSpeed = AccessTools.FieldRefAccess<MountedCargo, float>("pushSpeed");
        private static readonly AccessTools.FieldRef<MountedCargo, bool> CargoFired = AccessTools.FieldRefAccess<MountedCargo, bool>("fired");
        private static readonly FieldInfo MissileRailDirection = AccessTools.Field(typeof(MountedMissile), "railDirection");
        private static readonly AccessTools.FieldRef<MountedMissile, float> MissileRailSpeed = AccessTools.FieldRefAccess<MountedMissile, float>("railSpeed");
        private static readonly AccessTools.FieldRef<MountedMissile, float> MissileRailLength = AccessTools.FieldRefAccess<MountedMissile, float>("railLength");
        private static readonly AccessTools.FieldRef<MountedMissile, float> MissileRailDelay = AccessTools.FieldRefAccess<MountedMissile, float>("railDelay");

        private static MethodInfo buildCargo;
        private static Transform templates;
        private static WeaponMount spearhead;
        private static bool spearheadTried;
        private static readonly HashSet<string> Reported = new HashSet<string>();
        private static readonly Dictionary<WeaponInfo, WeaponMount> BayRacks = new Dictionary<WeaponInfo, WeaponMount>();
        private static readonly HashSet<WeaponMount> BayRejected = new HashSet<WeaponMount>();

        internal static void Install(Harmony h)
        {
            var plan = CurrentAirframeCompatibility.Family("SuperheavySpatialCargoPlan");
            var special = plan == null ? null : AccessTools.Method(plan, "HasSpecialCenterClearance");
            var qol = CurrentAirframeCompatibility.Family("SuperheavyQolStores");
            buildCargo = qol == null ? null : AccessTools.Method(qol, "BuildCargo");
            if (special != null) h.Patch(special, postfix: new HarmonyMethod(typeof(CourierCargoExpansion), nameof(AfterSpecialClearance)));
            else CurrentAirframeDamagePlugin.Log.LogWarning("Courier cargo expansion: spatial clearance not found; Spearhead not offered.");
            // before the family release planner and the Retro Kit / retro-only menu hooks (all at default or Last priority)
            h.Patch(AccessTools.Method(typeof(WeaponStation), nameof(WeaponStation.LaunchMount)),
                prefix: new HarmonyMethod(typeof(CourierCargoExpansion), nameof(BeforeLaunch)) { priority = Priority.First });
            h.Patch(AccessTools.Method(typeof(LoadoutSelector), nameof(LoadoutSelector.AssignAircraft)),
                prefix: new HarmonyMethod(typeof(CourierCargoExpansion), nameof(BeforeMenu)) { priority = Priority.First });
            h.Patch(AccessTools.Method(typeof(WeaponChecker), nameof(WeaponChecker.VetLoadout)),
                prefix: new HarmonyMethod(typeof(CourierCargoExpansion), nameof(BeforeVet)) { priority = Priority.First });
            var saved = AccessTools.TypeByName("SavedLoadout"); var create = saved == null ? null : AccessTools.Method(saved, "CreateLoadout", new[] { typeof(WeaponManager) });
            if (create != null)
                h.Patch(create, prefix: new HarmonyMethod(typeof(CourierCargoExpansion), nameof(BeforeSaved)) { priority = Priority.First });
        }

        // ---- 1. Spearhead clearance --------------------------------------------------------------------------------
        private static void AfterSpecialClearance(object item, Vector3 size, ref bool __result)
        {
            if (__result || item == null) return;
            var id = Traverse.Create(item).Field("Id").GetValue<string>();
            if (id == null) return;
            if (id.StartsWith("JP_RDK_", StringComparison.Ordinal)) id = id.Substring(7);
            if (id != SpearheadKey) return;
            // hold study: 9.73 x 4.19 x 4.29 m; the release box adds the native collider and, with the Retro Kit, the kit frame
            __result = size.z <= 10.40f && size.x <= 4.60f && size.y + .03f <= 4.40f;
        }

        // ---- hooks ------------------------------------------------------------------------------------------------
        private static bool IsCourier(AircraftDefinition d) => d != null && d.jsonKey == CourierKey;
        private static bool IsCourier(Aircraft a) => a != null && IsCourier(a.definition);

        private static void BeforeMenu(Aircraft __0) { if (IsCourier(__0)) Ensure(__0.weaponManager); }
        private static void BeforeVet(AircraftDefinition __0) { if (IsCourier(__0)) Ensure(null); }
        private static void BeforeSaved(WeaponManager __0)
        {
            var a = __0 == null ? null : __0.GetComponentInParent<Aircraft>(true);
            if (a == null || IsCourier(a)) Ensure(__0);
        }

        private static void Ensure(WeaponManager shown)
        {
            try
            {
                if (Encyclopedia.i == null || Encyclopedia.WeaponLookup == null) return;
                var managers = new List<WeaponManager>();
                foreach (var d in Encyclopedia.i.aircraft)
                    if (IsCourier(d) && d.unitPrefab != null && d.unitPrefab.GetComponent<Aircraft>() is Aircraft p && p.weaponManager != null)
                        managers.Add(p.weaponManager);
                if (shown != null && !managers.Contains(shown)) managers.Add(shown);
                var m = Spearhead();
                foreach (var manager in managers)
                {
                    if (manager?.hardpointSets == null) continue;
                    if (m != null)
                        foreach (var set in manager.hardpointSets)
                            // the Retro Kit variant replaces the base one (PreferRetro); do not bring the base back
                            if (set?.weaponOptions != null && !set.weaponOptions.Contains(m) && set.weaponOptions.Any(IsTankCargo)
                                && !set.weaponOptions.Any(o => o != null && o.jsonKey == "JP_RDK_" + SpearheadKey))
                                set.weaponOptions.Add(m);
                    PopulateBay(manager);
                }
            }
            catch (Exception e) { CurrentAirframeDamagePlugin.Log.LogWarning("Courier cargo expansion: " + e); }
        }

        private static bool IsTankCargo(WeaponMount mount)
        {
            var key = mount?.jsonKey ?? "";
            if (key.StartsWith("JP_RDK_", StringComparison.Ordinal)) key = key.Substring(7);
            return key == DonorKey;
        }

        private static WeaponMount Spearhead()
        {
            if (spearhead != null || spearheadTried) return spearhead;
            if (Encyclopedia.WeaponLookup.TryGetValue(SpearheadKey, out var existing) && existing != null) return spearhead = existing;
            if (buildCargo == null || !Encyclopedia.WeaponLookup.TryGetValue(DonorKey, out var donor) || donor == null) return null;
            spearheadTried = true;
            VehicleDefinition vehicle = null;
            if (Encyclopedia.Lookup != null && Encyclopedia.Lookup.TryGetValue("MBT1", out var unit)) vehicle = unit as VehicleDefinition;
            if (vehicle == null && Encyclopedia.Lookup != null)
                vehicle = Encyclopedia.Lookup.Values.OfType<VehicleDefinition>().FirstOrDefault(v => v != null && v.unitName == "Spearhead MBT");
            if (vehicle == null || vehicle.unitPrefab == null)
            {
                CurrentAirframeDamagePlugin.Log.LogWarning("Courier Spearhead cargo: native MBT1 not found.");
                return null;
            }
            var mount = buildCargo.Invoke(null, new object[] { donor, vehicle, SpearheadKey }) as WeaponMount;
            if (mount == null)
            {
                CurrentAirframeDamagePlugin.Log.LogWarning("Courier Spearhead cargo: excluded by the spatial clearance check.");
                return null;
            }
            var index = Encyclopedia.i.IndexLookup;
            ((INetworkDefinition)mount).LookupIndex = index.Count;
            index.Add(mount);
            Encyclopedia.i.weaponMounts.Add(mount);
            Encyclopedia.WeaponLookup[SpearheadKey] = mount;
            var plan = CurrentAirframeCompatibility.Family("SuperheavySpatialCargoPlan");
            object item = null;
            var measure = plan == null ? null : AccessTools.Method(plan, "TryMeasure");
            if (measure != null) { var args = new object[] { mount, null }; if ((bool)measure.Invoke(null, args)) item = args[1]; }
            string size = item == null ? "?" : $"{Traverse.Create(item).Field("Length").GetValue<float>():F2} x {Traverse.Create(item).Field("Width").GetValue<float>():F2} x {Traverse.Create(item).Field("Height").GetValue<float>():F2} m";
            CurrentAirframeDamagePlugin.Log.LogInfo($"Courier Spearhead cargo registered: {SpearheadKey}, {vehicle.unitName}, {vehicle.mass / 1000f:F1} t, stowed {size}.");
            return spearhead = mount;
        }

        // ---- 2. release tempo --------------------------------------------------------------------------------------
        private static void BeforeLaunch(WeaponStation __instance, Unit __0)
        {
            try
            {
                if (__instance == null || !__instance.Cargo || !(__0 is Aircraft aircraft) || !IsCourier(aircraft)) return;
                bool air = !OnGround(aircraft);
                foreach (var w in __instance.Weapons)
                    if (w is MountedCargo cargo && cargo != null && !CargoFired(cargo))
                    {
                        CargoRailSpeed(cargo) = air ? AirRailSpeed : GroundRailSpeed;
                        CargoRailDelay(cargo) = RailDelay;
                        CargoPushSpeed(cargo) = PushSpeed;
                    }
            }
            catch (Exception e) { CurrentAirframeDamagePlugin.Log.LogWarning("Courier cargo tempo: " + e.Message); }
        }

        private static bool OnGround(Aircraft aircraft)
        {
            foreach (var gear in aircraft.GetComponentsInChildren<LandingGear>(true))
                if (gear != null && gear.enabled && gear.WeightOnWheel(.01f)) return true;
            if (aircraft.partLookup != null)
                foreach (var part in aircraft.partLookup)
                    if (part != null)
                        foreach (var gear in part.GetComponentsInChildren<LandingGear>(true))
                            if (gear != null && gear.enabled && gear.WeightOnWheel(.01f)) return true;
            return false;
        }

        // ---- 3. weapons bay ----------------------------------------------------------------------------------------
        // The Ventral Weapons Bay (one station at the aircraft origin) already holds the vanilla attack weapons that fit,
        // each packed in the hold by the 16/11 bay plan (doors, exit corridors and neighbours checked per round; owner
        // decision then: no PAB-125, no PAB-250, no air-to-air missiles). A new weapon reuses the validated round
        // positions of an existing bay option whose store box contains its own store box on every axis: a smaller store
        // centred where a larger one passed every check passes them too. Among such options the one with most rounds
        // is used. The same exclusions apply to weapons from other mods.
        private sealed class Slots { internal Vector3 Size; internal Vector3[] Centers; internal string Key; }
        private static readonly AccessTools.FieldRef<MountedMissile, float> MissileDoorOpen = AccessTools.FieldRefAccess<MountedMissile, float>("doorOpenDuration");
        private static readonly AccessTools.FieldRef<MountedMissile, BayDoor[]> MissileBayDoors = AccessTools.FieldRefAccess<MountedMissile, BayDoor[]>("bayDoors");

        private static void PopulateBay(WeaponManager manager)
        {
            var bay = manager.hardpointSets.FirstOrDefault(s => s != null && s.name == "Ventral Weapons Bay" && s.weaponOptions != null);
            if (bay == null) return;
            var slots = new List<Slots>();
            foreach (var option in bay.weaponOptions)
            {
                if (option == null || option.prefab == null || (option.jsonKey ?? "").StartsWith(BayPrefix + "x_", StringComparison.Ordinal)) continue;
                var rails = option.prefab.GetComponentsInChildren<MountedMissile>(true);
                if (rails.Length == 0) continue;
                var centers = new List<Vector3>(); var size = Vector3.zero; bool ok = true;
                foreach (var r in rails)
                {
                    if (!TryBounds(r.gameObject, option.prefab.transform, out var b)) { ok = false; break; }
                    centers.Add(b.center); size = Vector3.Max(size, b.size);
                }
                if (ok) slots.Add(new Slots { Size = size, Centers = centers.ToArray(), Key = option.jsonKey });
            }
            if (slots.Count == 0) return;
            var present = new HashSet<WeaponInfo>(bay.weaponOptions.Where(o => o != null && o.info != null).Select(o => o.info));
            int added = 0;
            foreach (var source in Encyclopedia.i.weaponMounts.ToArray())
            {
                if (source == null || BayRejected.Contains(source)) continue;
                if (source.info != null && present.Contains(source.info) && !BayRacks.ContainsKey(source.info)) { BayRejected.Add(source); continue; }
                if (!(source.info != null && BayRacks.TryGetValue(source.info, out var rack)) && !TryBuildRack(source, slots, out rack)) { BayRejected.Add(source); continue; }
                if (rack != null && !bay.weaponOptions.Contains(rack)) { bay.weaponOptions.Add(rack); present.Add(rack.info); added++; }
            }
            if (added > 0)
                CurrentAirframeDamagePlugin.Log.LogInfo($"Courier weapons bay: {added} weapons added ({string.Join(", ", bay.weaponOptions.Where(o => o != null && o.jsonKey.StartsWith(BayPrefix + "x_")).Select(o => o.mountName))}).");
        }

        private static bool Excluded(WeaponInfo info)
        {
            if (info == null || info.gun || info.cargo || info.troops || info.jammer || info.energy || info.sling || !(info.missile || info.bomb)) return true;
            string name = (info.weaponName ?? "").ToUpperInvariant();
            if (name.StartsWith("PAB-125") || name.StartsWith("PAB-250")) return true; // owner decision 16/11/2026
            var role = info.effectiveness; // air-to-air: rated against aircraft above surface and radar targets
            return role.antiAir > 0f && role.antiAir >= role.antiSurface && role.antiAir >= role.antiRadar;
        }

        private static bool TryBuildRack(WeaponMount source, List<Slots> slots, out WeaponMount rack)
        {
            rack = null;
            string key = source.jsonKey ?? "";
            if (source.prefab == null || source.info == null || source.Cargo || !source.info.useWeaponDoors || Excluded(source.info) ||
                key.StartsWith(BayPrefix, StringComparison.Ordinal) || key.StartsWith("jp_superheavy_", StringComparison.Ordinal) ||
                key.StartsWith("JP_RDK_", StringComparison.Ordinal) || !Indexed(source))
                return false;
            var rails = source.prefab.GetComponentsInChildren<MountedMissile>(true);
            if (rails.Length == 0 || rails.Any(r => r.info != source.info) || source.prefab.GetComponentsInChildren<Weapon>(true).Length != rails.Length)
                return false;
            var rail = rails[0];
            if (!TryBounds(rail.gameObject, source.prefab.transform, out var store)) return false;
            var template = slots.Where(s => store.size.x <= s.Size.x + .001f && store.size.y <= s.Size.y + .001f && store.size.z <= s.Size.z + .001f)
                .OrderByDescending(s => s.Centers.Length).FirstOrDefault();
            if (template == null) return false;

            if (templates == null)
            {
                var root = new GameObject("Courier bay rack templates"); root.SetActive(false); Object.DontDestroyOnLoad(root);
                templates = root.transform;
            }
            string rackKey = BayPrefix + "x_" + key.ToLowerInvariant();
            if (Encyclopedia.WeaponLookup.TryGetValue(rackKey, out var known) && known != null) { BayRacks[source.info] = rack = known; return true; }
            var prefab = new GameObject(rackKey);
            prefab.transform.SetParent(templates, false);
            var railLocal = source.prefab.transform.InverseTransformPoint(rail.transform.position);
            var railRotation = Quaternion.Inverse(source.prefab.transform.rotation) * rail.transform.rotation;
            for (int i = 0; i < template.Centers.Length; i++)
            {
                var copy = Object.Instantiate(rail.gameObject, prefab.transform, false);
                copy.name = "Native round " + (i + 1);
                copy.transform.localRotation = railRotation;
                copy.transform.localPosition = railLocal - store.center + template.Centers[i];
                // same release as the authored bay rounds (BakeCourierBayOptions.Finish): drop 2 m at 3 m/s, door held 12 s
                var m = copy.GetComponent<MountedMissile>();
                if (MissileRailDirection != null) MissileRailDirection.SetValue(m, Enum.ToObject(MissileRailDirection.FieldType, 1));
                MissileRailLength(m) = 2f; MissileRailSpeed(m) = 3f; MissileRailDelay(m) = 0f; MissileDoorOpen(m) = 12f; MissileBayDoors(m) = new BayDoor[0];
            }
            var mount = Object.Instantiate(source);
            mount.name = mount.jsonKey = rackKey;
            mount.prefab = prefab;
            mount.ammo = template.Centers.Length;
            mount.mass = source.mass * mount.ammo / Mathf.Max(1, source.ammo);
            mount.mountName = source.info.weaponName + " x" + mount.ammo;
            mount.GearSafety = true; mount.GroundSafety = true;
            var index = Encyclopedia.i.IndexLookup;
            ((INetworkDefinition)mount).LookupIndex = index.Count;
            index.Add(mount);
            Encyclopedia.i.weaponMounts.Add(mount);
            Encyclopedia.WeaponLookup[rackKey] = mount;
            BayRacks[source.info] = rack = mount;
            if (Reported.Add(rackKey))
                CurrentAirframeDamagePlugin.Log.LogInfo($"Courier weapons bay rack {rackKey}: {mount.ammo} x {source.info.weaponName} from {key} in the validated positions of {template.Key} (store {store.size.x:F2} x {store.size.y:F2} x {store.size.z:F2} m within {template.Size.x:F2} x {template.Size.y:F2} x {template.Size.z:F2} m).");
            return true;
        }
        private static bool Indexed(INetworkDefinition item)
        {
            var index = Encyclopedia.i.IndexLookup;
            return item.LookupIndex is int slot && slot >= 0 && slot < index.Count && ReferenceEquals(index[slot], item);
        }

        // primary-LOD mesh bounds of root's renderers expressed in frame's local space (rack prefabs are centred on it)
        private static bool TryBounds(GameObject root, Transform frame, out Bounds result)
        {
            result = default; bool any = false;
            if (root == null) return false;
            var lower = new HashSet<Renderer>(); var primary = new HashSet<Renderer>();
            foreach (var group in root.GetComponentsInChildren<LODGroup>(true))
            {
                var lods = group.GetLODs(); if (lods.Length == 0) continue;
                primary.UnionWith(lods[0].renderers); foreach (var lod in lods.Skip(1)) lower.UnionWith(lod.renderers);
            }
            lower.ExceptWith(primary);
            foreach (var r in root.GetComponentsInChildren<MeshRenderer>(true))
            {
                if (!r.enabled || lower.Contains(r) || !r.TryGetComponent<MeshFilter>(out var f) || f.sharedMesh == null) continue;
                var b = f.sharedMesh.bounds;
                for (int c = 0; c < 8; c++)
                {
                    var p = frame.InverseTransformPoint(r.transform.TransformPoint(new Vector3(
                        (c & 1) == 0 ? b.min.x : b.max.x, (c & 2) == 0 ? b.min.y : b.max.y, (c & 4) == 0 ? b.min.z : b.max.z)));
                    if (any) result.Encapsulate(p); else { result = new Bounds(p, Vector3.zero); any = true; }
                }
            }
            return any;
        }
    }
